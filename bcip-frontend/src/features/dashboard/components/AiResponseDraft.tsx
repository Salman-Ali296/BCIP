"use client";

import { Check, Copy, Sparkles, RefreshCw } from "lucide-react";
import { useState, useEffect } from "react";

type Tone = "empathetic" | "formal" | "concise";

export function AiResponseDraft({
    suggestedResponse,
}: {
    suggestedResponse?: string | null;
}) {
    const [tone, setTone] = useState<Tone>("empathetic");
    const [draft, setDraft] = useState(suggestedResponse ?? "");
    const [copied, setCopied] = useState(false);
    const [error, setError] = useState("");

    // Generate alternate tones from base draft
    useEffect(() => {
        if (!suggestedResponse) return;
        if (tone === "empathetic") {
            setDraft(suggestedResponse);
        } else if (tone === "formal") {
            setDraft(
                `Dear Valued Partner,\n\nPlease accept this formal acknowledgement regarding your recent notification. We have evaluated the records under enterprise audit protocol. Remedial action has been authorized and dispatched per our service-level agreement.\n\nShould you require further executive escalation, our dedicated desk remains available.\n\nRespectfully,\nEnterprise Operations Team`
            );
        } else if (tone === "concise") {
            setDraft(
                `Hi,\n\nWe verified this incident. The remedial fix and adjustment have been processed immediately. Tracking/confirmation details have been dispatched to your primary email.\n\nThanks,\nSupport Operations`
            );
        }
        setCopied(false);
    }, [tone, suggestedResponse]);

    async function copyDraft() {
        try {
            await navigator.clipboard.writeText(draft);
            setCopied(true);
            setError("");
        } catch {
            setCopied(false);
            setError("Could not copy the draft. Select and copy the text manually.");
        }
    }

    return (
        <section className="mt-6 border-t border-slate-200/80 pt-6">
            <div className="flex items-center justify-between">
                <div className="flex items-center gap-2">
                    <span className="flex h-6 w-6 items-center justify-center rounded-md bg-blue-100 text-blue-700">
                        <Sparkles className="h-3.5 w-3.5" />
                    </span>
                    <h3 className="font-semibold text-slate-900 text-sm">AI Response Generator</h3>
                </div>
                <div className="flex items-center rounded-lg border border-slate-200 bg-slate-50 p-0.5 text-xs font-medium text-slate-600">
                    <button
                        type="button"
                        onClick={() => setTone("empathetic")}
                        className={`rounded-md px-2.5 py-1 transition ${
                            tone === "empathetic"
                                ? "bg-white text-blue-600 shadow-xs font-semibold"
                                : "hover:text-slate-900"
                        }`}
                    >
                        Empathetic
                    </button>
                    <button
                        type="button"
                        onClick={() => setTone("formal")}
                        className={`rounded-md px-2.5 py-1 transition ${
                            tone === "formal"
                                ? "bg-white text-blue-600 shadow-xs font-semibold"
                                : "hover:text-slate-900"
                        }`}
                    >
                        Formal
                    </button>
                    <button
                        type="button"
                        onClick={() => setTone("concise")}
                        className={`rounded-md px-2.5 py-1 transition ${
                            tone === "concise"
                                ? "bg-white text-blue-600 shadow-xs font-semibold"
                                : "hover:text-slate-900"
                        }`}
                    >
                        Concise
                    </button>
                </div>
            </div>
            <p className="mt-1.5 text-xs leading-5 text-slate-500">
                Context-aware draft generated by NLP engine. Human review required before dispatching to customer.
            </p>
            {draft ? (
                <>
                    <textarea
                        value={draft}
                        onChange={(event) => {
                            setDraft(event.target.value);
                            setCopied(false);
                        }}
                        aria-label="Edit suggested customer reply"
                        className="mt-3 min-h-36 w-full rounded-xl border border-slate-200 bg-slate-50/60 p-3.5 font-sans text-sm leading-6 text-slate-800 shadow-inner focus:border-blue-500 focus:bg-white focus:outline-none focus:ring-2 focus:ring-blue-100"
                    />
                    <div className="mt-2.5 flex items-center justify-between">
                        <button
                            type="button"
                            onClick={() => void copyDraft()}
                            disabled={!draft.trim()}
                            className="inline-flex items-center gap-2 rounded-lg bg-blue-600 px-3.5 py-2 text-xs font-semibold text-white shadow-xs hover:bg-blue-700 disabled:opacity-50 transition"
                        >
                            {copied ? <Check className="h-3.5 w-3.5 text-white" /> : <Copy className="h-3.5 w-3.5" />}
                            {copied ? "Copied to clipboard" : "Copy response draft"}
                        </button>
                        <span className="text-[11px] text-slate-400">
                            Tone: <strong className="capitalize text-slate-600">{tone}</strong>
                        </span>
                    </div>
                    {error && <p role="alert" className="mt-2 text-xs text-rose-700">{error}</p>}
                </>
            ) : (
                <p className="mt-3 rounded-lg bg-slate-50 p-3 text-sm text-slate-600">
                    A reply draft is unavailable for this complaint. Review the details and write a response manually.
                </p>
            )}
        </section>
    );
}

